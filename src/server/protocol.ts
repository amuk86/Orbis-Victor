import { currentPlayer, HUMAN_ID, transition } from '../game/engine';
import type { Command, GameEvent, GameState, RNG } from '../game/engine';
import { nextNpcAction } from '../game/npc';
import {replayFrame} from '../cloud/replay';
import type {ReplayFrame} from '../cloud/replay';

export class ApiError extends Error {
  constructor(public status: number, message: string) { super(message); }
}
export const NPC_BATCH_LIMIT = 64;
export type CloudCommand = Command | { type:'npc-step' } | { type:'npc-batch' } | { type:'launch'; source:string; target:string };
export type CampaignRecord = {
  ownerId:string; revision:number; eventCount:number; historyPages:number;
  state:Omit<GameState,'events'>; status:'ready'|'deleting';
  provenance:'cloud'|'local-import'; createdAt:string; updatedAt:string;
  lastRequestId:string; lastRequestHash:string;
  lastRequestFirstPage?:number;
};
export const requireOwner = (record:CampaignRecord, uid:string) => {
  if (record.ownerId!==uid) throw new ApiError(403,'Only the campaign owner can change or delete it.');
  if (record.status!=='ready') throw new ApiError(410,'This campaign is being deleted.');
};
export function object(value:unknown): Record<string,unknown> {
  if (!value || typeof value!=='object' || Array.isArray(value)) throw new ApiError(400,'Expected a JSON object.');
  return value as Record<string,unknown>;
}
export function exactKeys(value:Record<string,unknown>, allowed:string[]) {
  if (Object.keys(value).some(k=>!allowed.includes(k))) throw new ApiError(400,'Unexpected request fields. Send a command, never state, ownership, or dice.');
}
export function text(value:unknown, name:string, max=128):string {
  if (typeof value!=='string' || !value.length || value.length>max) throw new ApiError(400,`Invalid ${name}.`);
  return value;
}
export function integer(value:unknown, name:string, max=Number.MAX_SAFE_INTEGER):number {
  if (!Number.isSafeInteger(value) || (value as number)<0 || (value as number)>max) throw new ApiError(400,`Invalid ${name}.`);
  return value as number;
}
export function commandFrom(value:unknown):CloudCommand {
  const c=object(value), type=text(c.type,'command type',24);
  if (['roll','stop','end','npc-step','npc-batch'].includes(type)) { exactKeys(c,['type']); return {type} as CloudCommand; }
  if (type==='reinforce') {
    exactKeys(c,['type','country','amount']);
    const amount=c.amount===undefined?1:integer(c.amount,'amount');
    if(amount<1)throw new ApiError(400,'Amount must be positive.');
    return {type,country:text(c.country,'country',2),amount};
  }
  if (['transfer','attack','launch'].includes(type)) {
    exactKeys(c,type==='transfer'?['type','source','target','amount']:['type','source','target']);
    const source=text(c.source,'source',2),target=text(c.target,'target',2);
    if(type==='transfer') {
      const amount=c.amount===undefined?1:integer(c.amount,'amount');
      if(amount<1)throw new ApiError(400,'Amount must be positive.');
      return {type,source,target,amount};
    }
    return {type,source,target} as CloudCommand;
  }
  throw new ApiError(400,'Unknown command.');
}
export function applyCommand(record:CampaignRecord, uid:string, expectedRevision:number, command:CloudCommand, rng:RNG): {state:GameState;events:GameEvent[];actions:number;frames?:ReplayFrame[]} {
  requireOwner(record,uid);
  if(record.revision!==expectedRevision)throw new ApiError(409,'The campaign changed on another device. Refresh before making your next move.');
  let state:GameState={...record.state,events:[]};
  if(state.phase==='finished')throw new ApiError(400,'This campaign has ended.');
  const player=currentPlayer(state);
  if(command.type==='npc-step'||command.type==='npc-batch') {
    if(player.human)throw new ApiError(400,'It is the human commander’s turn.');
    const limit=command.type==='npc-batch'?NPC_BATCH_LIMIT:1;
    let actions=0,bytes=0;const frames:ReplayFrame[]=[];
    while(actions<limit&&bytes<1_000_000&&state.phase!=='finished'&&!currentPlayer(state).human){
      const action=nextNpcAction(state);
      if(!action)throw new ApiError(400,'No NPC action is available.');
      const result=transition(state,action,rng,record.eventCount);
      if(result.error)throw new ApiError(400,result.error);
      if(command.type==='npc-batch'){
        const frame=replayFrame(state,result.state);frames.push(frame);
        bytes+=Buffer.byteLength(JSON.stringify(frame))+Buffer.byteLength(JSON.stringify(result.events));
      }
      state=result.state;actions++;
    }
    return {state,events:state.events,actions,...(command.type==='npc-batch'?{frames}:{})};
  }
  if(player.id!==HUMAN_ID)throw new ApiError(400,'Wait for your turn. NPC decisions are generated by the server.');
  const first=command.type==='launch'?{type:'attack' as const,source:command.source,target:command.target}:command;
  let result=transition(state,{...first,actorId:HUMAN_ID},rng,record.eventCount);
  if(result.error)throw new ApiError(400,result.error);
  state=result.state;
  if(command.type==='launch') {
    result=transition(state,{type:'roll',actorId:HUMAN_ID},rng,record.eventCount);
    if(result.error)throw new ApiError(400,result.error);
    state=result.state;
  }
  return {state,events:state.events,actions:command.type==='launch'?2:1};
}
